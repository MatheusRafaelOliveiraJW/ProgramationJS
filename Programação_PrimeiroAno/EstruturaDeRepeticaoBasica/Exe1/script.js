// Uma escola técnica está desenvolvendo um sistema para demonstrar o 
// funcionamento da estrutura de repetição do...while.
// ●Desenvolva um programa em JavaScript que exiba todos os números 
// inteiros de 1 até 10, utilizando exclusivamente a estrutura do...while.

let x = 1;

do {
    console.log(x);
    x++;
} while (x <= 10)